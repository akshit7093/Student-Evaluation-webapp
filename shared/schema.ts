import { pgTable, text, serial, integer, boolean, timestamp, varchar, json } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod";
import { relations } from "drizzle-orm";

// Define role enum
export const UserRole = {
  GHOST: "ghost",
  FOUNDER: "founder",
  ADMIN: "admin",
  CENTER_MANAGER: "center_manager",
  PROJECT_INTERN: "project_intern",
  TEACHING_INTERN: "teaching_intern",
} as const;

// Users table
export const users = pgTable("users", {
  id: serial("id").primaryKey(),
  username: text("username").notNull().unique(),
  password: text("password").notNull(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  role: text("role").notNull().default(UserRole.TEACHING_INTERN),
  profileImage: text("profile_image"),
  active: boolean("active").notNull().default(true),
  createdAt: timestamp("created_at").defaultNow(),
});

export const insertUserSchema = createInsertSchema(users).omit({
  id: true,
  createdAt: true,
});

export const usersRelations = relations(users, ({ many }) => ({
  staff: many(staff),
  attendanceMarked: many(attendance, { relationName: "markedByUser" }),
  reportsGenerated: many(reports, { relationName: "reportGenerator" }),
}));

// Educational Centers table
export const centers = pgTable("centers", {
  id: serial("id").primaryKey(),
  name: text("name").notNull(),
  address: text("address").notNull(),
  city: text("city").notNull().default("Delhi"),
  location: json("location").notNull(), // { lat: number, lng: number }
  managerId: integer("manager_id").references(() => users.id),
  totalStudents: integer("total_students").notNull().default(0),
  totalStaff: integer("total_staff").notNull().default(0),
  active: boolean("active").notNull().default(true),
  createdAt: timestamp("created_at").defaultNow(),
});

export const insertCenterSchema = createInsertSchema(centers).omit({
  id: true,
  totalStudents: true,
  totalStaff: true,
  createdAt: true,
});

export const centersRelations = relations(centers, ({ many, one }) => ({
  students: many(students),
  staff: many(staff),
  manager: one(users, { fields: [centers.managerId], references: [users.id] }),
  attendance: many(attendance),
  reports: many(reports),
  aiInsights: many(aiInsights),
}));

// Students table
export const students = pgTable("students", {
  id: serial("id").primaryKey(),
  name: text("name").notNull(),
  studentId: varchar("student_id", { length: 15 }).notNull().unique(),
  centerId: integer("center_id").references(() => centers.id).notNull(),
  gender: text("gender").notNull(),
  age: integer("age").notNull(),
  grade: text("grade").notNull(),
  school: text("school"),
  guardianName: text("guardian_name").notNull(),
  contactNumber: text("contact_number"),
  address: text("address"),
  enrollmentDate: timestamp("enrollment_date").defaultNow(),
  performanceRating: text("performance_rating").default("Average"),
  attendancePercentage: integer("attendance_percentage").default(0),
  active: boolean("active").notNull().default(true),
});

// Create the base schema for inserting students
const baseInsertStudentSchema = createInsertSchema(students).omit({
  id: true,
  studentId: true, // Will be generated by the server
  performanceRating: true, // Default values
  attendancePercentage: true, // Default values
  enrollmentDate: true, // Will use the default value
});

// Extend the schema to make some fields optional with default values
export const insertStudentSchema = baseInsertStudentSchema.extend({
  school: z.string().nullable().optional(),
  contactNumber: z.string().nullable().optional(),
  address: z.string().nullable().optional(),
  active: z.boolean().default(true).optional(),
});

export const studentsRelations = relations(students, ({ one, many }) => ({
  center: one(centers, { fields: [students.centerId], references: [centers.id] }),
  attendance: many(attendance),
}));

// Staff table
export const staff = pgTable("staff", {
  id: serial("id").primaryKey(),
  userId: integer("user_id").references(() => users.id).notNull(),
  centerId: integer("center_id").references(() => centers.id).notNull(),
  position: text("position").notNull(),
  joiningDate: timestamp("joining_date").defaultNow(),
  active: boolean("active").notNull().default(true),
});

export const insertStaffSchema = createInsertSchema(staff).omit({
  id: true,
  joiningDate: true,
});

export const staffRelations = relations(staff, ({ one }) => ({
  user: one(users, { fields: [staff.userId], references: [users.id] }),
  center: one(centers, { fields: [staff.centerId], references: [centers.id] }),
}));

// Attendance table
export const attendance = pgTable("attendance", {
  id: serial("id").primaryKey(),
  studentId: integer("student_id").references(() => students.id).notNull(),
  centerId: integer("center_id").references(() => centers.id).notNull(),
  date: timestamp("date").defaultNow(),
  status: text("status").notNull().default("present"), // "present", "absent", "late", "excused"
  markedBy: integer("marked_by").references(() => users.id),
});

export const insertAttendanceSchema = createInsertSchema(attendance).omit({
  id: true,
  date: true,
}).extend({
  status: z.enum(["present", "absent", "late", "excused"]).default("present"),
  centerId: z.number().int().positive({ message: "Center ID is required" }),
});

export const attendanceRelations = relations(attendance, ({ one }) => ({
  student: one(students, { fields: [attendance.studentId], references: [students.id] }),
  center: one(centers, { fields: [attendance.centerId], references: [centers.id] }),
  marker: one(users, { fields: [attendance.markedBy], references: [users.id], relationName: "markedByUser" }),
}));

// Reports table
export const reports = pgTable("reports", {
  id: serial("id").primaryKey(),
  title: text("title").notNull(),
  centerId: integer("center_id").references(() => centers.id),
  type: text("type").notNull(), // e.g., 'monthly', 'quarterly', 'student_performance'
  content: json("content").notNull(),
  generatedBy: integer("generated_by").references(() => users.id).notNull(),
  generatedAt: timestamp("generated_at").defaultNow(),
});

export const insertReportSchema = createInsertSchema(reports).omit({
  id: true,
  generatedAt: true,
});

export const reportsRelations = relations(reports, ({ one }) => ({
  center: one(centers, { fields: [reports.centerId], references: [centers.id] }),
  generator: one(users, { fields: [reports.generatedBy], references: [users.id], relationName: "reportGenerator" }),
}));

// AI Insights table
export const aiInsights = pgTable("ai_insights", {
  id: serial("id").primaryKey(),
  title: text("title").notNull(),
  description: text("description").notNull(),
  category: text("category").notNull(), // e.g., 'performance', 'attendance', 'resource'
  centerId: integer("center_id").references(() => centers.id),
  data: json("data"),
  generatedAt: timestamp("generated_at").defaultNow(),
});

export const insertAiInsightSchema = createInsertSchema(aiInsights).omit({
  id: true,
  generatedAt: true,
});

export const aiInsightsRelations = relations(aiInsights, ({ one }) => ({
  center: one(centers, { fields: [aiInsights.centerId], references: [centers.id] }),
}));

// Export types
export type User = typeof users.$inferSelect;
export type InsertUser = z.infer<typeof insertUserSchema>;

export type Center = typeof centers.$inferSelect;
export type InsertCenter = z.infer<typeof insertCenterSchema>;

export type Student = typeof students.$inferSelect;
export type InsertStudent = z.infer<typeof insertStudentSchema>;

export type Staff = typeof staff.$inferSelect;
export type InsertStaff = z.infer<typeof insertStaffSchema>;

export type Attendance = typeof attendance.$inferSelect;
export type InsertAttendance = z.infer<typeof insertAttendanceSchema>;

export type Report = typeof reports.$inferSelect;
export type InsertReport = z.infer<typeof insertReportSchema>;

export type AiInsight = typeof aiInsights.$inferSelect;
export type InsertAiInsight = z.infer<typeof insertAiInsightSchema>;
